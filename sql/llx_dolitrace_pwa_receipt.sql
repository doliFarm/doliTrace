-- Records sent by the field app (PWA): the identifier generated by the phone makes a second sending of the same record
-- return the record already created instead of a duplicate.
CREATE TABLE IF NOT EXISTS llx_dolitrace_pwa_receipt(
	rowid			integer AUTO_INCREMENT PRIMARY KEY NOT NULL,
	entity			integer DEFAULT 1 NOT NULL,
	client_id		varchar(64) NOT NULL,				-- identifier generated by the phone
	element			varchar(32) NOT NULL,				-- operation, harvest
	fk_object		integer NOT NULL,
	fk_user			integer NOT NULL,
	date_client		datetime,							-- when the record was made on the phone
	datec			datetime NOT NULL
) ENGINE=innodb;
